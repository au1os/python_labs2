"""
Точка входа в консольное приложение управления арендой квартир.
Запускает CLI интерфейс.

Этот модуль является entry point приложения - он:
1. Импортирует необходимые классы из других модулей
2. Создаёт экземпляр приложения (бизнес-логика)
3. Создаёт и запускает CLI интерфейс
4. Обрабатывает исключения (прерывание, ошибки)
"""

from pathlib import Path  # Для работы с путями файлов
import sys  # Для доступа к системным параметрам

# Добавляем путь к lab01 для импорта базового класса Apartment
# Это необходимо, чтобы использовать класс Apartment из первой лабораторной
lab01_path = Path(__file__).parent.parent / "lab01"
sys.path.insert(0, str(lab01_path))

# Импортируем классы приложения
from app import ApartmentApp  # Бизнес-логика: управление коллекцией квартир
from cli import ApartmentCLI  # CLI-интерфейс: меню, ввод/вывод
from storage import DEFAULT_STORAGE_PATH  # Путь к файлу для сохранения данных


def main() -> None:
    """
    Основная функция приложения.
    Создаёт экземпляр приложения и запускает CLI.
    
    Логика работы:
    1. Выводит заголовок приложения
    2. Создаёт объект ApartmentApp с путём к файлу хранения
    3. Создаёт объект ApartmentCLI для взаимодействия с пользователем
    4. Запускает основной цикл CLI
    5. Обрабатывает прерывания и исключения
    """
    # Вывод заголовка приложения
    print("=" * 60)
    print("  СИСТЕМА УПРАВЛЕНИЯ АРЕНДОЙ КВАРТИР")
    print("  Лабораторная работа №7")
    print("=" * 60)
    print()
    
    # Создание приложения с путем к файлу хранения
    # DEFAULT_STORAGE_PATH указывает, где хранить данные (JSON файл)
    storage_path = DEFAULT_STORAGE_PATH
    app = ApartmentApp(storage_path)
    
    # Создание и запуск CLI
    # ApartmentCLI принимает экземпляр ApartmentApp для доступа к бизнес-логике
    cli = ApartmentCLI(app)
    
    try:
        # Запуск основного цикла CLI
        # Метод run() содержит бесконечный цикл с меню
        cli.run()
    except KeyboardInterrupt:
        # Обработка прерывания (Ctrl+C)
        print("\n\n⚠️  Принудительное завершение работы")
        # Пытаемся сохранить данные при прерывании
        try:
            if app.count > 0:  # Если есть квартиры в коллекции
                app.save_data()  # Сохраняем в JSON файл
                print("✅ Данные сохранены")
        except Exception:
            # Игнорируем ошибки сохранения при прерывании
            pass
        print("👋 До свидания!")
    except Exception as e:
        # Обработка непредвиденных исключений
        print(f"\n❌ Неожиданная ошибка: {e}")
        print("   Пожалуйста, сообщите разработчику")
        sys.exit(1)  # Завершаем приложение с кодом ошибки


if __name__ == "__main__":
    # Точка входа в приложение
    # Этот код выполняется только если файл запущен напрямую
    main()
