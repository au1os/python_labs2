"""
Модуль содержит собственные исключения для предметной области "Аренда квартир".
Все исключения наследуются от базового ApartmentError.

Иерархия исключений:
    Exception (базовый класс Python)
        └── ApartmentError (базовое исключение предметной области)
                ├── ApartmentNotFoundError (квартира не найдена)
                ├── DuplicateApartmentError (дубликат квартиры)
                ├── InvalidApartmentError (некорректные данные)
                ├── ApartmentOperationError (операция запрещена)
                ├── StorageError (ошибка сохранения/загрузки)
                └── ConfirmationError (операция отменена)
"""

from typing import Optional  # Для указания, что код ошибки может быть None


class ApartmentError(Exception):
    """
    Базовое исключение для всех ошибок предметной области "Аренда квартир".
    
    Это абстрактный базовый класс для всех специфичных исключений.
    Все исключения в приложении должны наследоваться от этого класса.
    
    Attributes:
        message (str): Сообщение об ошибке, описывающее проблему
        code (Optional[str]): Код ошибки для идентификации типа проблемы
    """
    
    def __init__(self, message: str, code: Optional[str] = None):
        """
        Инициализация базового исключения.
        
        Args:
            message: Сообщение об ошибке, которое будет показано пользователю
            code: Опциональный код ошибки (например, "NOT_FOUND", "DUPLICATE")
        """
        self.message = message  # Сохраняем сообщение в атрибут
        self.code = code  # Сохраняем код ошибки
        super().__init__(self.message)  # Вызываем конструктор базового класса Exception
    
    def __str__(self) -> str:
        """
        Возвращает строковое представление исключения.
        
        Если задан код ошибки, возвращает в формате "[CODE] message"
        Иначе возвращает только сообщение.
        
        Returns:
            str: Форматированное сообщение об ошибке
        """
        if self.code:
            # Возвращаем с кодом ошибки в квадратных скобках
            return f"[{self.code}] {self.message}"
        return self.message  # Возвращаем только сообщение


class ApartmentNotFoundError(ApartmentError):
    """
    Исключение возникает, когда квартира не найдена в коллекции.
    
    Используется в случаях:
    - Поиск квартиры по адресу не дал результатов
    - Попытка получить квартиру по несуществующему индексу
    - Попытка удалить/изменить несуществующую квартиру
    """
    
    def __init__(self, identifier: str, search_by: str = "адресу"):
        """
        Инициализация исключения "квартира не найдена".
        
        Args:
            identifier: Идентификатор, по которому искали квартиру
                       (адрес, индекс или другой критерий)
            search_by: Критерий поиска (по умолчанию "адресу")
                      Может быть "индексу", "ID" и т.д.
        """
        # Формируем понятное сообщение об ошибке
        message = f"Квартира по {search_by} '{identifier}' не найдена"
        # Вызываем конструктор базового класса с кодом "NOT_FOUND"
        super().__init__(message, code="NOT_FOUND")


class DuplicateApartmentError(ApartmentError):
    """
    Исключение возникает при попытке добавить дубликат квартиры.
    
    Используется когда:
    - Квартира с таким же адресом и площадью уже существует в коллекции
    - Метод __eq__ класса Apartment возвращает True для сравниваемых объектов
    """
    
    def __init__(self, address: str, area: float):
        """
        Инициализация исключения "дубликат квартиры".
        
        Args:
            address: Адрес дублирующейся квартиры
            area: Площадь дублирующейся квартиры (в м²)
        """
        # Формируем сообщение с указанием конкретных параметров
        message = f"Квартира с адресом '{address}' и площадью {area} м² уже существует"
        # Вызываем конструктор базового класса с кодом "DUPLICATE"
        super().__init__(message, code="DUPLICATE")


class InvalidApartmentError(ApartmentError):
    """
    Исключение возникает при некорректных данных квартиры.
    
    Используется когда:
    - Площадь <= 0 или не является числом
    - Цена <= 0 или не является числом
    - Адрес пустой или состоит только из пробелов
    - Срок аренды <= 0 или не является целым числом
    """
    
    def __init__(self, field: str, value: str, reason: str):
        """
        Инициализация исключения "некорректные data".
        
        Args:
            field: Название поля, в котором произошла ошибка
                  (например, "площадь", "цена", "адрес", "срок аренды")
            value: Некорректное значение, которое ввёл пользователь
            reason: Причина, по которой значение считается некорректным
                   (например, "должно быть положительным числом")
        """
        # Формируем подробное сообщение об ошибке
        message = f"Некорректное значение поля '{field}': {value}. {reason}"
        # Вызываем конструктор базового класса с кодом "INVALID_DATA"
        super().__init__(message, code="INVALID_DATA")


class ApartmentOperationError(ApartmentError):
    """
    Исключение возникает при невозможности выполнить операцию над квартирой.
    
    Используется когда:
    - Попытка изменить арендованную квартиру (изменение запрещено)
    - Попытка сдать уже арендованную квартиру
    - Попытка освободить свободную квартиру
    """
    
    def __init__(self, operation: str, reason: str):
        """
        Инициализация исключения "операция запрещена".
        
        Args:
            operation: Название операции, которую нельзя выполнить
                      (например, "изменить", "сдать в аренду", "освободить")
            reason: Причина, по которой операция запрещена
                   (например, "квартира уже арендована")
        """
        # Формируем сообщение с указанием операции и причины
        message = f"Невозможно выполнить '{operation}': {reason}"
        # Вызываем конструктор базового класса с кодом "OPERATION_DENIED"
        super().__init__(message, code="OPERATION_DENIED")


class StorageError(ApartmentError):
    """
    Исключение возникает при ошибках сохранения/загрузки данных.
    
    Используется когда:
    - Не удаётся прочитать файл (файл повреждён, нет прав)
    - Не удаётся записать файл (нет прав, диск заполнен)
    - Некорректный формат данных в файле
    """
    
    def __init__(self, operation: str, details: str):
        """
        Инициализация исключения "ошибка хранилища".
        
        Args:
            operation: Тип операции, которая не удалась
                      (например, "save", "load", "clear")
            details: Детали ошибки (сообщение от системы или библиотеки)
        """
        # Формируем сообщение с указанием операции и деталей
        message = f"Ошибка {operation}: {details}"
        # Вызываем конструктор базового класса с кодом "STORAGE_ERROR"
        super().__init__(message, code="STORAGE_ERROR")


class ConfirmationError(ApartmentError):
    """
    Исключение возникает при отмене операции пользователем.
    
    Используется когда:
    - Пользователь ответил "нет" на запрос подтверждения
    - Пользователь прервал операцию (например, нажал Ctrl+C)
    """
    
    def __init__(self, operation: str):
        """
        Инициализация исключения "операция отменена".
        
        Args:
            operation: Название операции, которая была отменена
                      (например, "удаление", "выход", "изменение")
        """
        # Формируем сообщение об отмене операции
        message = f"Операция '{operation}' отменена пользователем"
        # Вызываем конструктор базового класса с кодом "CANCELLED"
        super().__init__(message, code="CANCELLED")
